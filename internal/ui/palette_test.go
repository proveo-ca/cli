package ui

import (
	"fmt"
	"go/format"
	"io"
	"net/http"
	"os"
	"path/filepath"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"testing"
	"time"

	"github.com/proveo-ca/proveo/internal/testx"
)

const identityURL = "https://raw.githubusercontent.com/proveo-ca/identity/main/proveo.puml"

var identityVar = regexp.MustCompile(`(?m)^!\$([A-Z0-9_]+)\s*=\s*"#([0-9A-Fa-f]{6})"`)

type identityColour struct {
	name string
	rgb  int
}

func identityColours(src string) []identityColour {
	var out []identityColour
	for _, m := range identityVar.FindAllStringSubmatch(src, -1) {
		rgb, _ := strconv.ParseInt(m[2], 16, 32)
		out = append(out, identityColour{goName(m[1]), int(rgb)})
	}
	slices.SortFunc(out, func(a, b identityColour) int { return strings.Compare(a.name, b.name) })
	return out
}

// goName turns ACCENT_1 into IdentityAccent1.
func goName(v string) string {
	var b strings.Builder
	b.WriteString("Identity")
	for part := range strings.SplitSeq(strings.ToLower(v), "_") {
		if part != "" {
			b.WriteString(strings.ToUpper(part[:1]) + part[1:])
		}
	}
	return b.String()
}

func renderPalette(src string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("// Code generated by `go test ./internal/ui -run TestPaletteMatchesIdentity -update`; DO NOT EDIT.\n")
	b.WriteString("// SPEC: _spec/_conventions/tui-design-language.puml\n\npackage ui\n\n")
	b.WriteString("// Identity* are proveo-ca/identity proveo.puml's colours, layer 0 of the theme.\nconst (\n")
	for _, c := range identityColours(src) {
		fmt.Fprintf(&b, "\t%s = 0x%06X\n", c.name, c.rgb)
	}
	b.WriteString(")\n")
	return format.Source([]byte(b.String()))
}

func TestPaletteMatchesIdentity(t *testing.T) {
	snapshot := filepath.Join("testdata", "identity.puml")
	if *testx.Update {
		client := http.Client{Timeout: 15 * time.Second}
		resp, err := client.Get(identityURL)
		if err != nil {
			t.Fatal(err)
		}
		defer resp.Body.Close()
		body, err := io.ReadAll(resp.Body)
		if err != nil || resp.StatusCode != http.StatusOK {
			t.Fatalf("fetch %s: %s %v", identityURL, resp.Status, err)
		}
		if err := os.WriteFile(snapshot, body, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	src, err := os.ReadFile(snapshot)
	if err != nil {
		t.Fatal(err)
	}
	if n := len(identityColours(string(src))); n < 10 {
		t.Fatalf("%s holds %d colours; the identity parse is broken", snapshot, n)
	}
	want, err := renderPalette(string(src))
	if err != nil {
		t.Fatal(err)
	}
	if *testx.Update {
		if err := os.WriteFile("palette.go", want, 0o644); err != nil {
			t.Fatal(err)
		}
	}
	got, err := os.ReadFile("palette.go")
	if err != nil || string(got) != string(want) {
		t.Errorf("palette.go drifted from %s (%v): run go test ./internal/ui -run TestPaletteMatchesIdentity -update", snapshot, err)
	}
}

func TestColoursComeFromTheIdentity(t *testing.T) {
	src, err := os.ReadFile(filepath.Join("testdata", "identity.puml"))
	if err != nil {
		t.Fatal(err)
	}
	known := map[int]bool{}
	for _, c := range identityColours(string(src)) {
		known[c.rgb] = true
	}
	for name, v := range map[string]int{
		"ColorApp": ColorApp, "ColorAsync": ColorAsync, "ColorHost": ColorHost, "ColorCloud": ColorCloud,
		"ColorDB": ColorDB, "ColorError": ColorError, "ColorSuccess": ColorSuccess, "ColorMuted": ColorMuted,
		"ColorAccentBright": ColorAccentBright, "ColorWhite": ColorWhite,
	} {
		if !known[v] {
			t.Errorf("%s = #%06X is not an identity colour", name, v)
		}
	}
	if known[ColorSurface] {
		t.Error("ColorSurface is now an identity colour: point it at the palette and drop the exception")
	}
}
